export function issueText(issue: ImportIssue, locale: Locale): string {
  const message = messages[locale][issue.code];
  if (typeof message === 'string') return message;

  const field = issue.field && protocolFields.has(issue.field) ? issue.field : undefined;
  return message({ field, keys: safeIssueKeys(issue.keys ?? []) });
}
