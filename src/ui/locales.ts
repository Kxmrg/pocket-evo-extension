export const dictionaries = { en, zh, fr, de, es } satisfies Record<Locale, Record<MessageKey, string>>;

export function resolveLocale(languages: readonly string[]): Locale {
  const code = languages[0]?.toLowerCase().split('-')[0] ?? '';
  return Object.hasOwn(dictionaries, code) ? code as Locale : 'en';
}

export function createText(locale: Locale): (
  key: MessageKey, values?: Readonly<Record<string, string | number>>,
) => string {
  return (key, values) => dictionaries[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values && Object.hasOwn(values, name) ? String(values[name]) : placeholder,
  );
}
